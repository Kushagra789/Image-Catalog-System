import io

import streamlit as st

from .. import fixtures
from ..catalog import CatalogError
from ..visualization import draw_objects
from .common import display_size, get_service, load_image, source_legend, status_badge


def _detection_options(prefix: str) -> dict:
    c1, c2, c3 = st.columns(3)
    auto = c1.checkbox("Detect objects automatically", value=True, key=f"{prefix}_auto")
    use_yolo = c2.checkbox("Use YOLO", value=True, key=f"{prefix}_yolo", disabled=not auto)
    conf = c3.slider("YOLO confidence threshold", 0.05, 0.9, 0.25, 0.05, key=f"{prefix}_conf",
                     disabled=not (auto and use_yolo),
                     help="Lower values find more objects (useful for cartoons) but add false positives.")
    use_ill = c2.checkbox("Use illustration model", value=True, key=f"{prefix}_ill", disabled=not auto,
                          help="YOLOE with a curated vocabulary; runs only on cartoons/clip-art.")
    return {"auto_detect": auto, "use_yolo": use_yolo, "yolo_confidence": conf, "use_illustration_model": use_ill}


def _show_outcome(name: str, outcome) -> None:
    svc = get_service()
    rec = outcome.record
    with st.container(border=True):
        c1, c2 = st.columns([1, 2])
        with c1:
            img = load_image(rec)
            if img is not None:
                objs = svc.db.list_objects(rec.id)
                st.image(display_size(draw_objects(img, objs)), width="stretch")
        with c2:
            st.markdown(f"**#{rec.id} · {rec.display_name}** ({rec.width}×{rec.height}) from `{name}`")
            status_badge(rec.detection_status)
            if outcome.detection is None:
                st.caption("Detection not run (you can run it on the Object Detection page).")
            else:
                d = outcome.detection
                msg = {"success": st.success, "empty": st.warning, "failed": st.error}.get(d.status, st.info)
                msg(d.message)
                for r in d.reports:
                    st.caption(f"{'✅' if r.ok else '⚠️'} {r.engine}: {r.message}")


def page() -> None:
    svc = get_service()
    st.title("Upload Images")
    st.caption("Images are stored in the local `data/images` folder; their metadata goes into SQLite.")

    tab_upload, tab_fixtures = st.tabs(["Upload your images", "Synthetic test images"])

    with tab_upload:
        files = st.file_uploader(
            "Choose images (PNG, JPG, WEBP, BMP, GIF, TIFF)",
            type=["png", "jpg", "jpeg", "webp", "bmp", "gif", "tif", "tiff"],
            accept_multiple_files=True,
        )
        display_name = ""
        if files and len(files) == 1:
            display_name = st.text_input("Display name (optional)", placeholder=files[0].name)
        opts = _detection_options("up")
        allow_dup = st.checkbox("Allow duplicate files", value=False,
                                help="By default an identical file that is already in the catalog is skipped.")
        if st.button("Add to catalog", type="primary", disabled=not files):
            for f in files:
                with st.spinner(f"Processing {f.name}..."):
                    try:
                        outcome = svc.upload(
                            f.getvalue(), f.name, display_name or None,
                            auto_detect=opts["auto_detect"], allow_duplicates=allow_dup,
                            use_yolo=opts["use_yolo"], yolo_confidence=opts["yolo_confidence"],
                            use_illustration_model=opts["use_illustration_model"],
                        )
                    except CatalogError as exc:
                        st.error(f"{f.name}: {exc}")
                        continue
                    except Exception as exc:  # keep processing the other files
                        st.error(f"{f.name}: unexpected error: {exc}")
                        continue
                _show_outcome(f.name, outcome)
            source_legend()

    with tab_fixtures:
        st.markdown(
            "Reproducible drawings generated by code (`imagecat/fixtures.py`). They are **not photos**: "
            "they exercise shape/colour analysis, manual correction and composition. "
            "For semantic detection (e.g. *apple*, *orange*, *person*) upload real photographs."
        )
        names = st.multiselect("Fixtures", list(fixtures.FIXTURES), default=list(fixtures.FIXTURES))
        cols = st.columns(5)
        for i, name in enumerate(names):
            img, _ = fixtures.generate(name)
            img.thumbnail((200, 150))
            cols[i % 5].image(img, caption=name)
        opts_f = _detection_options("fx")
        if st.button("Add selected fixtures to catalog", type="primary", disabled=not names):
            for name in names:
                img, _ = fixtures.generate(name)
                buf = io.BytesIO()
                img.save(buf, format="PNG")
                try:
                    outcome = svc.upload(buf.getvalue(), f"{name}.png", name.replace("_", " "),
                                         auto_detect=opts_f["auto_detect"], use_yolo=opts_f["use_yolo"],
                                         yolo_confidence=opts_f["yolo_confidence"],
                                         use_illustration_model=opts_f["use_illustration_model"])
                except CatalogError as exc:
                    st.warning(f"{name}: {exc}")
                    continue
                _show_outcome(f"{name}.png", outcome)
            source_legend()
